import "server-only";
import { db } from "@/lib/db";
import { getNotifySettings } from "@/lib/settings";
import { dayStr, today } from "@/lib/dates";

export type ReminderDTO = {
  id: string;
  title: string;
  date: string;
  time: string;
  repeat: string;
  template: string;
  developerIds: string[];
  taskId: string;
  taskTitle: string;
  note: string;
  done: boolean;
  doneOn: string;
  sourceType: string;
  sourceId: string;
  autoGenerated: boolean;
  notified: boolean;
  projectId: string;
  projectName: string;
};

export type AutoData = {
  dailyOn: boolean;
  overdueOn: boolean;
  dailyTime: string;
  days: number[];
  /** developers without a daily update today */
  missingUpdates: { id: string; name: string }[];
  overdue: { id: string; name: string; n: number }[];
  /** today's planned meetings with a reminder */
  meetings: {
    id: string;
    title: string;
    type: string;
    date: string;
    startTime: string;
    remindMinutes: number;
    attendees: number;
    mode: string;
  }[];
};

/** What the Reminders page and the reminder banner need. */
export async function remindersData() {
  const cfg = await getNotifySettings();
  const D = today(),
    now = new Date(D);
  const [reminders, developers, overdue, standups, meetings] = await Promise.all([
    db.reminder.findMany({
      orderBy: [{ date: "asc" }, { time: "asc" }],
      include: {
        developers: true,
        task: { select: { title: true } },
        project: { select: { name: true } },
      },
    }),
    db.developer.findMany({ orderBy: { name: "asc" }, select: { id: true, name: true } }),
    db.taskAssignee.groupBy({
      by: ["developerId"],
      where: { task: { status: { not: "done" }, dueDate: { lt: now } } },
      _count: true,
    }),
    db.standup.findMany({ where: { date: now }, select: { developerId: true } }),
    db.meeting.findMany({
      where: { date: now, status: "Planned", remindMinutes: { gt: 0 } },
      include: { _count: { select: { developers: true } } },
    }),
  ]);

  const has = new Set(standups.map((s) => s.developerId));
  const auto: AutoData = {
    dailyOn: cfg.dailyOn,
    overdueOn: cfg.overdueOn,
    dailyTime: cfg.dailyTime,
    days: cfg.days,
    missingUpdates: developers.filter((d) => !has.has(d.id)),
    overdue: overdue
      .map((o) => ({
        id: o.developerId,
        name: developers.find((d) => d.id === o.developerId)?.name ?? "",
        n: o._count,
      }))
      .filter((o) => o.name),
    meetings: meetings.map((m) => ({
      id: m.id,
      title: m.title,
      type: m.type,
      date: dayStr(m.date),
      startTime: m.startTime,
      remindMinutes: m.remindMinutes ?? 0,
      attendees: m._count.developers + m.inviteeRecordIds.length,
      mode: m.mode,
    })),
  };

  const list: ReminderDTO[] = reminders.map((r) => ({
    id: r.id,
    title: r.title,
    date: dayStr(r.date),
    time: r.time,
    repeat: r.repeat || "none",
    template: r.template || "custom",
    developerIds: r.developers.map((d) => d.developerId),
    taskId: r.taskId ?? "",
    taskTitle: r.task?.title ?? "",
    note: r.note,
    done: r.done,
    doneOn: dayStr(r.doneOn),
    sourceType: r.sourceType || "manual",
    sourceId: r.sourceId || "",
    autoGenerated: r.autoGenerated || false,
    notified: r.notified || false,
    projectId: r.projectId ?? "",
    projectName: r.project?.name ?? "",
  }));

  return { reminders: list, auto, developers };
}
